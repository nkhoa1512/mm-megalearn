/**
 * Returns the best thumbnail image URL for a course or roadmap milestone.
 */
export function getCourseImage(course, fallbackCategory = '') {
  if (course?.milestoneImage) return course.milestoneImage;
  if (course?.thumbnail) return course.thumbnail;
  if (course?.imageUrl) return course.imageUrl;
  if (course?.coverImage) return course.coverImage;

  const domain = course?.domain || course?.category || fallbackCategory;
  if (domain && DOMAIN_FALLBACK_MAP[domain]) {
    return DOMAIN_FALLBACK_MAP[domain];
  }
  return DEFAULT_FALLBACK_IMAGE;
}
